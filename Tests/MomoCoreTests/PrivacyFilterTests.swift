import XCTest
@testable import MomoCore

final class PrivacyFilterTests: XCTestCase {
    func testConcealedDropped() {
        XCTAssertFalse(PrivacyFilter.shouldStore(pasteboardTypes: ["org.nspasteboard.ConcealedType"]))
    }
    func testTransientDropped() {
        XCTAssertFalse(PrivacyFilter.shouldStore(pasteboardTypes: ["org.nspasteboard.TransientType"]))
    }
    func testNormalKept() {
        XCTAssertTrue(PrivacyFilter.shouldStore(pasteboardTypes: ["public.utf8-plain-text"]))
    }
    func testMixedWithConcealedDropped() {
        XCTAssertFalse(PrivacyFilter.shouldStore(pasteboardTypes: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"]))
    }

    func testConcealedDroppedWhenNotAllowed() {
        // Passwords from a password manager stay out unless the user opts in.
        XCTAssertFalse(PrivacyFilter.shouldStore(pasteboardTypes: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"],
                                                 allowConcealed: false))
    }
    func testConcealedKeptWhenAllowed() {
        XCTAssertTrue(PrivacyFilter.shouldStore(pasteboardTypes: ["public.utf8-plain-text", "org.nspasteboard.ConcealedType"],
                                                allowConcealed: true))
    }
    func testTransientStillDroppedWhenConcealedAllowed() {
        // The opt-in covers passwords only; "don't record me" markers still win.
        XCTAssertFalse(PrivacyFilter.shouldStore(pasteboardTypes: ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType"],
                                                 allowConcealed: true))
    }
    func testAutoGeneratedStillDroppedWhenConcealedAllowed() {
        XCTAssertFalse(PrivacyFilter.shouldStore(pasteboardTypes: ["org.nspasteboard.AutoGeneratedType"],
                                                 allowConcealed: true))
    }
}
